const helpText = (isPrivate, owner, topic = "") => {
	if (topic === "管理" && !(isPrivate && owner)) return "管理说明请主人私聊发送 /帮助 管理。";
	if (topic && topic !== "全部") return topics[topic]?.join("\n") || "帮助分类：聊天、记忆、人格、媒体、数据、管理。例：/帮助 记忆";
	if (topic === "全部") return Object.entries(topics).filter(([key]) => key !== "管理" || isPrivate && owner).map(([, lines]) => lines.join("\n")).join("\n\n");
	return [
		"大肥鱼 · 帮助",
		isPrivate ? "直接说，或 /提问 问题。私聊是否开放由主人设置。" : "@我、喊“大肥鱼”，或 /提问 问题。",
		"/新会话：开始新话题；/取消：取消请求。",
		"/人格、/心情：查看当前设定。",
		"/语音 问题；/表情 标签；也可直接发图片或语音。",
		isPrivate ? "/记住 内容；/记忆；/个人密钥：管理自己的偏好或 Key。" : "/群记忆：查看本群记忆。",
		"/状态；/额度；/群密钥：群管理员绑定群 Key；/隐私说明。",
		isPrivate && owner ? "主人：/关闭 原因；/开启；/帮助 管理。" : "首次设置主人：私聊发送 /我是主人。",
		"详细用法：/帮助 聊天|记忆|人格|媒体|数据。"
	].join("\n");
};
var res_default = async () => {
	const [context, next] = useEvent({ selects: ["message.create", "private.message.create"] });
	const [route] = useRoute();
	next();
	if (!context.match.selects) return;
	const event = context.current;
	const [message] = useMessage();
	await message.send({ format: Format.create().addMarkdownOriginal(helpText(Boolean(event.IsPrivate), Boolean(event.IsMaster), route.rawArgs.join(" ").trim())) });
};

export { res_default as default, helpText };