var res_default = async () => {
	const [eventContext] = useEvent({ selects: ["message.create", "private.message.create"] });
	if (!eventContext.match.selects) return;
	const event = eventContext.current;
	const [message] = useMessage();
	await message.send({ format: Format.create().addMarkdownOriginal(event.IsPrivate ? event.IsMaster ? ownerPrivateHelp : "私聊：直接发送文字或 `/chat 问题`。是否开放由主人配置。\n`/new` 清空自己的会话；`/cancel` 取消自己的请求；`/agentprivacy` 查看数据说明。\n`/记住 内容` 保存偏好，`/记忆` 查看，`/忘记 编号` 或 `/忘记全部` 删除。" : groupHelp) });
};

export { res_default as default };